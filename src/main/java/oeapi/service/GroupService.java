package oeapi.service;

import java.util.List;

import java.util.Optional;
import java.util.UUID;

import jakarta.transaction.Transactional;
import oeapi.model.Group;
import oeapi.oeapiUtils;
import oeapi.repository.GroupRepository;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;

/**
 *
 * @author itziar.urrutia
 */
@Service
@Transactional
public class GroupService extends oeapiEndpointService<Group, GroupRepository> implements oeapiServiceInterface<Group> {

    public List<Group> getByOrganisationId(String id) {

        return repository.findByOrganisation_OrganisationId(id);

    }

    @Override
    public Group autoGenerateBasicItem(String id) {
        Group group = new Group();
        group.setGroupId(id);
        group.setName(oeapiUtils.defaultName());
        group.setDescription(oeapiUtils.defaultDescription());
        group.setAbbreviation("Autogenerated Group for Id: " + id);
        group.setPrimaryCode(oeapiUtils.defaultPrimaryCode("identifier", id + "-AutoGenerated"));
        group.setGroupType("class");

        return group;
    }

    @Override
    public Group autoGenerateBasicItem() {
        return this.autoGenerateBasicItem(UUID.randomUUID().toString() + "-Autogenerated-Group");
    }

    // ---- OEAPI v6 memberships -------------------------------------------------

    @org.springframework.beans.factory.annotation.Autowired
    private oeapi.repository.MembershipRepository membershipRepository;

    public List<oeapi.model.Membership> getMemberships(String groupId) {
        return membershipRepository.findByGroup_GroupId(groupId);
    }

    public java.util.Optional<oeapi.model.Membership> getMembership(String groupId, String personId) {
        return membershipRepository.findByGroup_GroupIdAndPerson_PersonId(groupId, personId);
    }

    public oeapi.model.Membership saveMembership(oeapi.model.Membership membership) {
        return membershipRepository.saveAndFlush(membership);
    }
}
